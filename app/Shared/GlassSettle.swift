// Волна 27 (тихий покой): снимок ui-53 — стеклянные кружки ряда «Альбом · Автомат · Дом · Трюки · Игры» то светлые,
// то тёмные. Liquid Glass выбирает светлый или тёмный вид по фону в момент, когда кнопку рисуют, и дальше держит его:
// в одном запуске 30 с подряд яркость кружков не менялась ни на единицу (RESEARCH/13-perf.md). Комната грузится
// асинхронно (RealityView make), поэтому кнопки смотрели то на пустой фон сцены, то на наполовину готовую комнату,
// то на готовую — смотря как быстро раннер её собрал.
//
// Только в UI-тестах: через `delay` после того, как сцена собрана, ряды кнопок пересоздаются (`.id(pass)`) и стекло
// заново смотрит на готовую комнату. У живого пользователя `pass` всегда 0 — вид прежний.

enum GlassSettle {
    /// Сколько ждать после make: комната успевает дойти до экрана и на медленном раннере.
    static let delay: Double = 1.5

    /// Номер прохода после очередной сборки сцены. В обычном запуске всегда 0: `.id` не меняется, кнопки не
    /// пересоздаются.
    static func next(_ pass: Int, uiTest: Bool) -> Int {
        uiTest ? pass + 1 : 0
    }

    /// Значение pet.stage для UI-тестов: уровни дома (HouseUITests ищут «bed=1») и номер прохода стекла.
    /// Вне UI-тестов — пусто: VoiceOver его не читает.
    static func stageValue(levels: String, pass: Int, uiTest: Bool) -> String {
        uiTest ? "\(levels) glass=\(pass)" : ""
    }

    /// Стекло уже пересмотрело готовую комнату: в значении pet.stage проход 1 и больше.
    static func settled(_ value: String) -> Bool {
        guard let r = value.range(of: "glass=") else { return false }
        let digits = value[r.upperBound...].prefix { $0.isNumber }
        return (Int(digits) ?? 0) >= 1
    }
}
